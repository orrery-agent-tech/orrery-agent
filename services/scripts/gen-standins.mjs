// Compiles the ORRY test stand-ins (test/contracts/OrryStandIns.sol) with the local solc and writes their ABI and
// bytecode to test/generated/standins.ts. Test deployments only. Run: node scripts/gen-standins.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "../test/contracts/OrryStandIns.sol");
const out = JSON.parse(
  execFileSync("solc", ["--combined-json", "abi,bin", "--optimize", "--evm-version", "cancun", src], { encoding: "utf8", maxBuffer: 32 << 20 }),
);
const version = execFileSync("solc", ["--version"], { encoding: "utf8" }).trim().split("\n").pop();
let ts = `// Generated by scripts/gen-standins.mjs (${version}). Test deployments only. Do not edit.\n`;
for (const name of ["OrryStandIn", "QuoteTreasuryStandIn", "CommitmentProbe"]) {
  const key = Object.keys(out.contracts).find((k) => k.endsWith(`:${name}`));
  const c = out.contracts[key];
  const abi = typeof c.abi === "string" ? JSON.parse(c.abi) : c.abi;
  const lower = name[0].toLowerCase() + name.slice(1);
  ts += `export const ${lower}Abi = ${JSON.stringify(abi)} as const;\n`;
  ts += `export const ${lower}Bytecode = "0x${c.bin}" as const;\n`;
}
writeFileSync(join(here, "../test/generated/standins.ts"), ts);
console.log("stand-ins written");

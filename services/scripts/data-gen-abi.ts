// Lane L2: writes the data contracts' interface ABIs into packages/shared/src/data.ts (between the generated-abi markers)
// and the full ABIs plus bytecode of the data contracts and their test stand-ins into test/generated/data.ts.
// Run after `forge build` in contracts/:  npx tsx scripts/data-gen-abi.ts
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
const lower = (name: string) => name[0]!.toLowerCase() + name.slice(1);
const artifact = (name: string, file: string) => {
  const art = JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
  if (art.bytecode.object.includes("__$")) throw new Error(`${name} needs library linking`);
  return art as { abi: unknown[]; bytecode: { object: string } };
};

const interfaces: [string, string][] = [
  ["IDataFeeSplitter", "IDataFeeSplitter.sol"],
  ["IDataProviderRegistry", "IDataProviderRegistry.sol"],
];
let block = "// <generated-abi> (services/scripts/data-gen-abi.ts writes this block from contracts/out; do not edit by hand)\n";
for (const [name, file] of interfaces) block += `export const ${lower(name)}Abi = ${JSON.stringify(artifact(name, file).abi)} as const;\n`;
block += "// </generated-abi>";
const sharedPath = join(here, "../packages/shared/src/data.ts");
const shared = readFileSync(sharedPath, "utf8");
const start = shared.indexOf("// <generated-abi>");
const end = shared.indexOf("// </generated-abi>");
if (start < 0 || end < 0) throw new Error("generated-abi markers missing in data.ts");
writeFileSync(sharedPath, shared.slice(0, start) + block + shared.slice(end + "// </generated-abi>".length));

const deployables: [string, string][] = [
  ["DataFeeSplitter", "DataFeeSplitter.sol"],
  ["DataProviderRegistry", "DataProviderRegistry.sol"],
  ["DataRewardPool", "DataMocks.sol"],
  ["DataStakeValue", "DataMocks.sol"],
  ["DataOrry", "DataMocks.sol"],
  ["DataTreasury", "DataMocks.sol"],
  ["DataEventEmitter", "DataMocks.sol"],
];
let code = "// Generated by scripts/data-gen-abi.ts from contracts/out. Development and test deployments only.\n";
for (const [name, file] of deployables) {
  const art = artifact(name, file);
  code += `export const ${lower(name)}Abi = ${JSON.stringify(art.abi)} as const;\n`;
  code += `export const ${lower(name)}Bytecode = "${art.bytecode.object}" as const;\n`;
}
mkdirSync(join(here, "../test/generated"), { recursive: true });
writeFileSync(join(here, "../test/generated/data.ts"), code);
console.log(`data ABIs: ${interfaces.length} interfaces into shared/src/data.ts, ${deployables.length} contracts into test/generated/data.ts`);

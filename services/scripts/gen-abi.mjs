// Reads Foundry artifacts from ../contracts/out and writes ABIs (and dev bytecode) for the TypeScript packages.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
const contracts = [
  ["OrreryPolicyModule", "OrreryPolicyModule.sol"],
  ["OrreryAttestor", "OrreryAttestor.sol"],
  ["OrreryLens", "OrreryLens.sol"],
  ["OrreryTreasury", "OrreryTreasury.sol"],
  ["DevUSDG", "DevUSDG.sol"],
  ["DevAccount7579", "DevAccount7579.sol"],
  ["MockIdentityRegistry", "Mocks.sol"],
  ["MockAccount7579", "Mocks.sol"],
  ["MockTarget", "Mocks.sol"],
];
// The ORRY contracts (lanes A and B) and the test helpers of their suites, for local deployments only. Their
// frozen interface ABIs stay in packages/shared/src/orry-abi.ts; these are the implementations' full ABIs.
const orry = [
  ["OrreryHook", "OrreryHook.sol"],
  ["EarnVault", "EarnVault.sol"],
  ["ClaimAll", "ClaimAll.sol"],
  ["OrryLens", "OrryLens.sol"],
  ["OrryStaking", "OrryStaking.sol"],
  ["OrryRewardsRouter", "OrryRewardsRouter.sol"],
  ["OrryBuyback", "OrryBuyback.sol"],
  ["OrreryTreasury", "OrreryTreasury.sol"],
  ["MockOrry", "EarnMocks.sol"],
  ["HubActor", "EarnMocks.sol"],
  ["EarnVaultFactory", "EarnVaultFactory.sol", { optional: true }], // multi-pair builds only (R-35)
  ["MockFeed", "EarnMocks.sol"], // a Chainlink stand-in: the hook's constructor needs an ETH/USD feed that answers
  // wave R1 markets and the development network's stand-ins (scripts/deploy-46630-full.ts)
  ["MarketFactory", "MarketFactory.sol", { optional: true }],
  ["FeeTiers", "FeeTiers.sol", { optional: true }],
  ["OrryPriceOracle", "OrryPriceOracle.sol", { optional: true }],
  ["DevRoundFeed", "DevRoundFeed.sol", { optional: true }],
  ["DevStockToken", "DevStockToken.sol", { optional: true }],
  // wave 3 facilitator (R-57, utility 11)
  ["MerchantSplitterFactory", "MerchantSplitterFactory.sol", { optional: true }],
  ["X402Permit2Proxy", "X402Permit2Proxy.sol", { optional: true }],
];

const lower = (name) => name[0].toLowerCase() + name.slice(1);
const artifact = (name, file) => {
  const art = JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
  if (art.bytecode.object.includes("__$")) throw new Error(`${name} needs library linking`);
  return art;
};

let abi = "// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\n";
let code = "// Generated by scripts/gen-abi.mjs. Development and test deployments only.\n";
for (const [name, file] of contracts) {
  const art = artifact(name, file);
  abi += `export const ${lower(name)}Abi = ${JSON.stringify(art.abi)} as const;\n`;
  code += `export const ${lower(name)}Bytecode = "${art.bytecode.object}" as const;\n`;
}

let rc = "// Generated by scripts/gen-abi.mjs from contracts/out. Development and test deployments only.\n";
for (const [name, file, opts] of orry) {
  if (opts?.optional && !existsSync(join(out, file, `${name}.json`))) continue;
  const art = artifact(name, file);
  rc += `export const ${lower(name)}Abi = ${JSON.stringify(art.abi)} as const;\n`;
  rc += `export const ${lower(name)}Bytecode = "${art.bytecode.object}" as const;\n`;
}
// Runtime of the live 4663 PoolManager (contracts/test/orry/earn/fixtures/PoolManagerCode.sol), set with
// anvil_setCode at its own address: the code carries NoDelegateCall's `original` immutable, so it works only there.
const fixture = readFileSync(join(here, "../../contracts/test/orry/earn/fixtures/PoolManagerCode.sol"), "utf8");
const pmAddress = fixture.match(/ADDRESS = (0x[0-9a-fA-F]{40});/)?.[1];
const runtime = fixture.slice(fixture.indexOf("RUNTIME")).match(/hex"([0-9a-f]*)"/g)?.map((h) => h.slice(4, -1)).join("");
if (!pmAddress || !runtime) throw new Error("PoolManagerCode.sol fixture not understood");
rc += `export const poolManagerAddress = "${pmAddress}" as const;\n`;
rc += `export const poolManagerRuntime = "0x${runtime}" as const;\n`;

writeFileSync(join(here, "../packages/shared/src/abi.ts"), abi);
mkdirSync(join(here, "../test/generated"), { recursive: true });
writeFileSync(join(here, "../test/generated/bytecode.ts"), code);
writeFileSync(join(here, "../test/generated/orry.ts"), rc);
console.log("abi and bytecode written for", contracts.length, "contracts; ORRY:", orry.length, "contracts and the PoolManager runtime");
